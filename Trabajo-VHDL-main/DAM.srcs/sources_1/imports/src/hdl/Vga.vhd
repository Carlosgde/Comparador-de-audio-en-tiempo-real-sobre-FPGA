            bit_idx  := col_index_i mod 8;

            case char_idx is
                when 0 => if CHAR_M(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
                when 1 => if CHAR_I(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
                when 2 => if CHAR_C(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
                when 3 => if CHAR_R(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
                when 4 => if CHAR_O(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
                when 5 => if CHAR_P(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
                when 6 => if CHAR_H(row_index_i)(bit_idx) = '1' then text_pixel <= x"1"; end if;
