           MIC_M_DATA_SD : IN STD_LOGIC_VECTOR(15 DOWNTO 0); -- Input microphone data
           MIC_M_CLK_RISING_SD  : buffer STD_LOGIC; -- Active when the data from the microphone is read
           
           aciertos_vga   : in integer;
           fallos_vga     : in integer
           );
end Vga;

